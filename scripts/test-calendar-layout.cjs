const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../abp/Dental/src/Dental.Web/Pages/Schedule/calendar-layout.js'), 'utf8'), context);
const layout = context.dentalCalendarLayout;
const plain = value => JSON.parse(JSON.stringify(value));
assert.deepEqual(plain(layout.position(570,585,480,1200)), {top:180,height:30});
assert.deepEqual(plain(layout.position(450,510,480,1200)), {top:0,height:60});
assert.equal(layout.position(1200,1230,480,1200), null);
assert.equal(layout.minuteAt(180,480,1200,15), 570);
assert.equal(layout.minuteAt(179,480,1200,15), 555);
assert.equal(layout.minuteAt(-30,480,1200,15), 480);
assert.equal(layout.minuteAt(2000,480,1200,15), 1185);
assert.deepEqual(plain(layout.lanes([{id:'a',start:180,end:210},{id:'b',start:210,end:240}])), {a:{lane:0,count:1},b:{lane:0,count:1}});
assert.deepEqual(plain(layout.lanes([{id:'a',start:180,end:240},{id:'b',start:210,end:270},{id:'c',start:240,end:300}])), {a:{lane:0,count:2},b:{lane:1,count:2},c:{lane:0,count:2}});
assert.deepEqual(plain(layout.lanes([{id:'a',start:0,end:10},{id:'b',start:0,end:10},{id:'c',start:0,end:10}])), {a:{lane:0,count:3},b:{lane:1,count:3},c:{lane:2,count:3}});
console.log('Calendar geometry: 10 checks passed');
